def _avoid_section(avoid) -> str:
    """人工否决过的词：拼进提示词，让模型别再提取。"""
    if not avoid:
        return ""
    words = "、".join(sorted(str(w) for w in avoid if str(w).strip()))
    if not words:
        return ""
    return f"\n【人工已否决的词（不要提取）】\n{words}\n"


